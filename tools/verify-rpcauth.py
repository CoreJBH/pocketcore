#!/usr/bin/env python3
"""Checks that Bitcoin Core 32.1 accepts the rpcauth line POCKETCORE writes.

Builds the exact conf NodeConfig.write produces (one rpcauth entry, no
rpcuser/rpcpassword) on regtest, then talks JSON-RPC with the plain
user/password pair the app uses.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import pathlib
import random
import shutil
import string
import subprocess
import time
import urllib.error
import urllib.request

BIN = pathlib.Path("/workspace/tmp/core/bitcoin-32.1/bin")
DIR = pathlib.Path("/workspace/tmp/pcrpcauth")
PORT = 48_999

ALPHABET = string.digits + string.ascii_letters  # same characters as RpcAuth
USER_TOKEN = "abcd1234efgh5678"
PASSWORD = "Aa2Bb3Cc4Dd5Ee6Ff7Gg8Hh9Jj2Kk3Ll"


def random_salt() -> str:
    return "".join(random.choice(ALPHABET) for _ in range(16))


def rpcauth_line(user: str, password: str, salt: str) -> str:
    digest = hmac.new(salt.encode("ascii"), password.encode("utf-8"), hashlib.sha256).hexdigest()
    return f"{user}:{salt}${digest}"


def rpc(user: str, password: str):
    body = json.dumps({"jsonrpc": "1.0", "id": "pocketcore", "method": "getblockchaininfo",
                       "params": []}).encode()
    token = base64.b64encode(f"{user}:{password}".encode()).decode()
    request = urllib.request.Request(
        f"http://127.0.0.1:{PORT}/", data=body,
        headers={"Content-Type": "application/json", "Authorization": f"Basic {token}"},
    )
    try:
        with urllib.request.urlopen(request, timeout=5) as response:
            return response.status, json.loads(response.read())
    except urllib.error.HTTPError as error:
        return error.code, error.read().decode()[:120]


def main() -> int:
    shutil.rmtree(DIR, ignore_errors=True)
    DIR.mkdir(parents=True)
    line = rpcauth_line(USER_TOKEN, PASSWORD, random_salt())
    conf = [
        "# Generated by PocketCore. Changes are overwritten on every start.",
        "server=1",
        "daemon=0",
        "regtest=1",
        f"rpcauth={line}",
        "prune=550",
        "dbcache=128",
        "maxconnections=8",
        "maxmempool=50",
        "persistmempool=1",
        "listen=1",
        "discover=0",
        "dnsseed=1",
        "uacomment=POCKETCORE",
        "disablewallet=1",
        "txindex=0",
        "blockfilterindex=0",
        "peerbloomfilters=0",
        "printtoconsole=0",
        "",
        "[regtest]",
        "rpcbind=127.0.0.1",
        "rpcallowip=127.0.0.1",
        f"rpcport={PORT}",
        "port=48900",
        "",
    ]
    (DIR / "bitcoin.conf").write_text("\n".join(conf))

    log = open(DIR / "stdout.log", "wb")
    process = subprocess.Popen(
        [str(BIN / "bitcoind"), f"-datadir={DIR}", f"-conf={DIR / 'bitcoin.conf'}",
         "-printtoconsole=0"],
        stdout=log, stderr=subprocess.STDOUT,
    )
    try:
        deadline = time.time() + 90
        status, payload = None, None
        while time.time() < deadline:
            try:
                status, payload = rpc(USER_TOKEN, PASSWORD)
                # -28 is "warming up": the node is answering, so auth worked.
                if status == 200:
                    break
                if isinstance(payload, dict) and payload.get("error", {}).get("code") != -28:
                    break
            except (urllib.error.URLError, ConnectionError, OSError):
                pass
            time.sleep(0.5)
        print("conf rpcauth:", line[:18] + "..." + line[-8:])
        if status != 200:
            print("FAIL: correct password rejected:", status, payload)
            print("---- debug.log tail ----")
            print((DIR / "regtest" / "debug.log").read_text()[-3000:] if (DIR / "regtest" / "debug.log").exists() else "(no debug.log)")
            print("---- stdout ----")
            print((DIR / "stdout.log").read_text()[-2000:])
            return 1
        print("correct password: HTTP", status, "chain =", payload["result"]["chain"],
              "blocks =", payload["result"]["blocks"])
        status, payload = rpc(USER_TOKEN, "wrong-password")
        print("wrong password: HTTP", status)
        if status == 200:
            print("FAIL: a wrong password was accepted")
            return 1
        return 0
    finally:
        process.terminate()
        try:
            process.wait(timeout=60)
        except subprocess.TimeoutExpired:
            process.kill()
        log.close()


if __name__ == "__main__":
    raise SystemExit(main())
